// A stroke font, for the names over the fighters' heads.
//
// Letters drawn as lines, the way everything else in the arena is drawn:
// there is no typeface here, only polylines on a 4 by 6 grid with the origin
// at the top left. They are scaled and placed by the scene, so a name at the
// back of the arena comes out as small as the fighter wearing it.
//
// Each glyph is a list of strokes, each stroke a list of points. Drawing one
// is a matter of walking the points -- the scene does that with the same
// segment pool it draws the fighters with, so a name costs what a few limbs
// cost and nothing else.
